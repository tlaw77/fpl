const OWNER_DATA='https://raw.githubusercontent.com/tlaw77/fpl/main/data/latest.json';
const oEsc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[c]));

function managerLabel(r){
  return `<strong>${oEsc(r.manager||'Unknown manager')}</strong><br><span class="subtle">${oEsc(r.team_name||'')}</span>`;
}

function applyOwnerNames(d){
  const managers=[{...(d.me||{}),picks:d.squad||[]},...(d.rivals||[])];
  const byEntry=new Map(managers.map(m=>[String(m.entry_id),m]));

  // Standings: row order follows rank; replace Team cell with owner first, team second.
  const sorted=[{...(d.me||{}),overlap_pct:100},...(d.rivals||[])].sort((a,b)=>(a.rank||999)-(b.rank||999));
  document.querySelectorAll('#rivals-table tbody tr').forEach((tr,i)=>{
    const r=sorted[i];
    if(!r)return;
    const td=tr.children[1];
    if(td)td.innerHTML=managerLabel(r);
  });
  const th=document.querySelector('#rivals-table thead th:nth-child(2)');
  if(th)th.textContent='Manager';

  // Nearest target card in "What matters now".
  const cards=[...document.querySelectorAll('#action-grid .action-card')];
  const nearest=[...(d.rivals||[])].filter(r=>(r.total_points||0)>(d.me?.total_points||0)).sort((a,b)=>(a.total_points||0)-(b.total_points||0))[0];
  const targetCard=cards.find(c=>c.querySelector('.action-label')?.textContent.trim()==='Nearest target');
  if(targetCard&&nearest){
    const strong=targetCard.querySelector('strong');
    if(strong)strong.innerHTML=`${oEsc(nearest.manager)} <span class="subtle-inline">(${oEsc(nearest.team_name)})</span> · ${(nearest.total_points||0)-(d.me?.total_points||0)} pts`;
  }

  // Rival overlap labels.
  const overlapRows=[...document.querySelectorAll('#overlap-list .overlap-row')];
  const overlapSorted=[...(d.rivals||[])].sort((a,b)=>(b.overlap_pct||0)-(a.overlap_pct||0));
  overlapRows.forEach((row,i)=>{
    const r=overlapSorted[i];
    if(!r)return;
    const first=row.children[0];
    if(first)first.innerHTML=`<strong>${oEsc(r.manager)}</strong><div class="subtle">${oEsc(r.team_name)} · ${r.overlap_count||0}/15 shared</div>`;
  });

  // Manager × player matrix labels: preserve row order (rank order).
  const matrixManagers=managers.sort((a,b)=>(a.rank||999)-(b.rank||999));
  const matrixRows=[...document.querySelectorAll('#manager-matrix .matrix-row:not(.matrix-head)')];
  matrixRows.forEach((row,i)=>{
    const r=matrixManagers[i];
    const cell=row.querySelector('.matrix-manager');
    if(cell&&r){
      cell.innerHTML=`<strong>${oEsc((r.manager||'').slice(0,22))}</strong><br><span class="matrix-team">${oEsc((r.team_name||'').slice(0,20))}</span>`;
      cell.title=`${r.manager||''} — ${r.team_name||''}`;
    }
  });

  // Rival targeting cards generated by relative.js / explainability layer.
  const targets=d.target_rivals||[];
  const targetCards=[...document.querySelectorAll('#target-rivals .action-card')];
  targetCards.forEach((card,i)=>{
    const r=targets[i]; if(!r)return;
    const strong=card.querySelector('strong');
    const sub=card.querySelector('.subtle');
    if(strong)strong.textContent=`#${r.rank} ${r.manager||'Unknown manager'}`;
    if(sub)sub.textContent=`${r.team_name||''} · ${Number(r.gap||0)>0?'+':''}${r.gap||0} pts vs you`;
  });
}

async function ownerNames(){
  try{
    const r=await fetch(`${OWNER_DATA}?t=${Date.now()}`,{cache:'no-store'});
    if(!r.ok)return;
    const d=await r.json();
    // Render after other dashboard layers; run twice because relative/explainability scripts also mutate the page.
    setTimeout(()=>applyOwnerNames(d),250);
    setTimeout(()=>applyOwnerNames(d),1000);
  }catch(e){console.warn('owner names layer',e)}
}
ownerNames();
